#!/usr/bin/env python3
"""Write `leananchors.tex`: the `\\leancheck{<label>}` command, which links a statement of the
course to its Lean formalization on the Lean pages.

    python3 scripts/lean_pages/leancheck.py [--url URL] [output.tex]

The Lean declarations of a label are those whose docstring cites it in its bold lead (see
`build.read_decls`); a section label is covered when a Lean module cites it in its title.
`\\leancheck{def:topo}` prints a small "Lean" mark linking to `<URL>#label=def:topo`. For a label
with no Lean declaration, it prints nothing and LaTeX warns. Default output: `leananchors.tex`
next to `M1_Analyse.tex`. Lean is not needed.

Switching websites: `\\leanmapurl` is set with `\\providecommand`, so a `\\newcommand\\leanmapurl{...}`
placed before `\\input{leananchors}` overrides it; `--url` changes the default written in the file.
"""
import argparse
import re
from pathlib import Path

from build import ROOT, read_decls

DEFAULT_URL = "https://mirebeau.github.io/lean-proof-maps/M1Analyse/"


def course_labels():
    """The `\\label{...}` keys of the course (no compilation needed)."""
    labels = set()
    for f in [ROOT / "M1_Analyse.tex", *ROOT.glob("Include/*.tex")]:
        labels |= set(re.findall(r"\\label\{([^}]*)\}", f.read_text(errors="replace")))
    return labels


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default=DEFAULT_URL, help="address of the Lean pages")
    ap.add_argument("output", nargs="?", default=str(ROOT / "leananchors.tex"))
    args = ap.parse_args()
    decls, modules = read_decls(course_labels())
    anchors = {}
    for d in decls:
        for l in d["labels"]:
            anchors.setdefault(l, []).append(d["short"])
    for m in modules:
        for l in m["labels"]:
            anchors.setdefault(l, []).append(m["module"])
    defs = "\n".join(f"\\@namedef{{leancheck@{l}}}{{{len(a)}}}% {', '.join(a)}"
                     for l, a in sorted(anchors.items()))
    Path(args.output).write_text(f"""\
% Generated by scripts/lean_pages/leancheck.py from the Lean files: do not edit by hand.
% Usage: \\input{{leananchors}} in the preamble, after hyperref; then \\leancheck{{<label>}} next to
% a formalized statement prints a "Lean" mark linking to its Lean formalization.
% Website: \\newcommand\\leanmapurl{{<address>}} before \\input{{leananchors}} overrides the default.
% Mark: likewise \\newcommand\\leancheckmark{{...}}.
\\providecommand\\leanmapurl{{{args.url}}}
\\providecommand\\leancheckmark{{\\textup{{\\textsf{{\\scriptsize Lean}}}}\\ensuremath{{^\\checkmark}}}}
\\makeatletter
\\DeclareRobustCommand\\leancheck[1]{{%  robust: usable in titles
  \\@ifundefined{{leancheck@#1}}%
    {{\\PackageWarning{{leananchors}}{{No Lean declaration for the label `#1'}}}}%
    {{\\href{{\\leanmapurl\\#label=#1}}{{\\leancheckmark}}}}}}
% label -> number of Lean declarations (their names)
{defs}
\\makeatother
""")
    print(f"{args.output}: {len(anchors)} labels with Lean declarations")


if __name__ == "__main__":
    main()
